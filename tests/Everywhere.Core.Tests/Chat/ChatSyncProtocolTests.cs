using Everywhere.Cloud;
using MessagePack;

namespace Everywhere.Core.Tests.Chat;

public sealed class ChatSyncProtocolTests
{
    [TestCase(null, ChatSyncFailureCode.Unknown)]
    [TestCase("future_code", ChatSyncFailureCode.Unknown)]
    public void Failure_WhenDiagnosticsAreOmitted_PreservesStructuredRejection(string? code, ChatSyncFailureCode expected)
    {
        // Error envelopes are a wire boundary: omitted diagnostics must not hide a server rejection.
        var fields = new Dictionary<string, object>();
        if (code is not null)
        {
            fields["code"] = code;
        }
        var bytes = MessagePackSerializer.Serialize(fields, cancellationToken: CancellationToken.None);
        var failure = MessagePackSerializer.Deserialize<ChatSyncFailure>(bytes, cancellationToken: CancellationToken.None);
        using (Assert.EnterMultipleScope())
        {
            Assert.That(failure.RawCode, Is.EqualTo(code ?? string.Empty));
            Assert.That(failure.Code, Is.EqualTo(expected));
            Assert.That(failure.Details, Is.Empty);
        }
    }

    [Test]
    public void Protocol_WhenDecodedFromTypeScript_PreservesIdentityAndExactCounters()
    {
        // The same fixture is asserted by the Worker tests; generated by @msgpack/msgpack.
        var wire = Convert.FromBase64String("h6hjb21taXRJZNkkMDAxMTIyMzMtNDQ1NS02Njc3LTg4OTktYWFiYmNjZGRlZWZmpmNoYXRJZNkkZmZlZWRkY2MtYmJhYS05OTg4LTc3NjYtNTU0NDMzMjIxMTAwsGV4cGVjdGVkUmV2aXNpb27PAB////////+2cmVxdWlyZWREYXRhR2VuZXJhdGlvbgGmYWN0aW9upnVwZGF0ZblleHBlY3RlZExpZmVjeWNsZVJldmlzaW9uAKppc0FyY2hpdmVkwg==");
        var header = MessagePackSerializer.Deserialize<ChatSyncUploadHeader>(wire);
        Assert.Multiple(() =>
        {
            Assert.That(header.CommitId, Is.EqualTo("00112233-4455-6677-8899-aabbccddeeff"));
            Assert.That(header.ChatId, Is.EqualTo("ffeeddcc-bbaa-9988-7766-554433221100"));
            Assert.That(header.ExpectedRevision, Is.EqualTo(ChatSyncProtocol.MaximumCounter));
            Assert.That(MessagePackSerializer.Serialize(header), Is.EqualTo(wire));
        });
    }
}