        }
        else if (settingsItemAttribute.GetNamedArgument("DocumentUrl") is { IsNull: false, Value: string documentUrl })
        {
            sb.AppendLine($"{itemName}.DocumentUrl = {ToLiteral(documentUrl)};");
        }

