    private static bool MigrateColoredIcons(JsonObject root)
    {
        var hasChanged = false;

        if (GetPathNode(root, "Model.CustomAssistants") is JsonArray assistants)
        {
            foreach (var entry in assistants)
            {
                if (entry is JsonObject assistantObj && assistantObj["Icon"] is JsonObject iconObj)
                {
                    hasChanged |= MigrateColoredIconObject(iconObj);
                }
            }
        }

        if (GetPathNode(root, "TextSelection.ToolbarActions") is JsonArray actions)
        {
            foreach (var entry in actions)
            {
                if (entry is not JsonObject actionObj)
                {
                    continue;
                }

                if (actionObj["Icon"] is JsonObject iconObj)
                {
                    hasChanged |= MigrateColoredIconObject(iconObj);
                }

                if (actionObj["IconOverride"] is JsonObject iconOverrideObj)
                {
                    hasChanged |= MigrateColoredIconObject(iconOverrideObj);
                }
            }
        }

        return hasChanged;
    }

    private static bool MigrateColoredIconObject(JsonObject iconObj)
    {
        var hasChanged = false;

        if (iconObj["Type"] is JsonValue typeValue)
        {
            if (typeValue.TryGetValue<string>(out var typeName) &&
                string.Equals(typeName, "Lucide", StringComparison.OrdinalIgnoreCase))
            {
                iconObj["Type"] = nameof(ColoredIconType.Tabler);
                hasChanged = true;
            }
        }

        if (iconObj["Kind"] is JsonValue kindValue)
        {
            if (kindValue.TryGetValue<string>(out var kindName))
            {
                TablerIconKind? mappedKind = null;
                if (Enum.TryParse<LegacyLucideIconKind>(kindName, ignoreCase: true, out var legacyKind))
                {
                    mappedKind = ((TablerIconKind)(int)legacyKind).Normalize();
                }
                else if (int.TryParse(kindName, out var numericFromString))
                {
                    mappedKind = ((TablerIconKind)numericFromString).Normalize();
                }

                if (mappedKind is { } resolved && Enum.IsDefined(resolved))
                {
                    var normalizedName = resolved.ToString();
                    if (!string.Equals(kindName, normalizedName, StringComparison.Ordinal))
                    {
                        iconObj["Kind"] = normalizedName;
                        hasChanged = true;
                    }
                }
            }
            else if (kindValue.TryGetValue<int>(out var numericId))
            {
                var resolved = ((TablerIconKind)numericId).Normalize();
                if (Enum.IsDefined(resolved))
                {
                    iconObj["Kind"] = resolved.ToString();
                    hasChanged = true;
                }
            }
        }

        return hasChanged;
    }

