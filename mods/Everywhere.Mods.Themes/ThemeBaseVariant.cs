namespace Everywhere.Mods.Themes;

/// <summary>
/// Identifies whether a theme targets a light or dark base polarity.
/// </summary>
public enum ThemeBaseVariant
{
    /// <summary>
    /// Targets light mode surfaces with dark foreground ink.
    /// </summary>
    Light,

    /// <summary>
    /// Targets dark mode surfaces with light foreground ink.
    /// </summary>
    Dark,
}
